CREATE OR REPLACE VIEW SRIRAM_VW_BATCH_PERFORMANCE AS
SELECT
    B.BATCH_ID,
    B.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.PRODUCT_FAMILY,
    B.PRODUCTION_LINE,
    L.LINE_NAME,
    B.SHIFT,
    B.PRODUCTION_DATE,
    B.PLANNED_QUANTITY,
    B.PRODUCED_QUANTITY,
    B.PRODUCED_QUANTITY - B.PLANNED_QUANTITY AS QUANTITY_VARIANCE,
    ROUND(
        B.PRODUCED_QUANTITY * 100.0 /
        NULLIF(B.PLANNED_QUANTITY, 0), 2
    ) AS PRODUCTION_ATTAINMENT_PERCENT,
    B.STATUS,
    COALESCE(D.DEFECT_COUNT, 0) AS DEFECT_COUNT,
    COALESCE(D.TOTAL_AFFECTED_QUANTITY, 0) AS TOTAL_AFFECTED_QUANTITY,
    COALESCE(D.TOTAL_INSPECTED_QUANTITY, 0) AS TOTAL_INSPECTED_QUANTITY,
    ROUND(
        D.TOTAL_AFFECTED_QUANTITY * 100.0 /
        NULLIF(D.TOTAL_INSPECTED_QUANTITY, 0), 2
    ) AS AFFECTED_QUANTITY_RATE_PERCENT
FROM SRIRAM_RAW.SRIRAM_PRODUCTION_BATCHES B
LEFT JOIN SRIRAM_RAW.SRIRAM_PRODUCTS P
    ON B.PRODUCT_ID = P.PRODUCT_ID
LEFT JOIN SRIRAM_RAW.SRIRAM_PRODUCTION_LINES L
    ON B.PRODUCTION_LINE = L.PRODUCTION_LINE
LEFT JOIN (
    SELECT
        BATCH_ID,
        COUNT(*) AS DEFECT_COUNT,
        SUM(AFFECTED_QUANTITY) AS TOTAL_AFFECTED_QUANTITY,
        SUM(INSPECTED_QUANTITY) AS TOTAL_INSPECTED_QUANTITY
    FROM SRIRAM_RAW.SRIRAM_DEFECTS
    GROUP BY BATCH_ID
) D
    ON B.BATCH_ID = D.BATCH_ID;

