CREATE OR REPLACE VIEW SRIRAM_VW_MACHINE_PERFORMANCE AS
SELECT
    M.MACHINE_ID,
    M.MACHINE_NAME,
    M.MACHINE_TYPE,
    M.MACHINE_STATUS,

    COUNT(E.EVENT_ID) AS TOTAL_EVENTS,
    COUNT(DISTINCT E.BATCH_ID) AS BATCHES_PROCESSED,
    COUNT(DISTINCT E.OPERATOR_ID) AS OPERATORS_INVOLVED,
    COUNT(DISTINCT E.EVENT_TYPE) AS EVENT_TYPES,

    SUM(E.QUANTITY) AS TOTAL_EVENT_QUANTITY,
    MIN(E.EVENT_TIMESTAMP) AS FIRST_EVENT,
    MAX(E.EVENT_TIMESTAMP) AS LAST_EVENT

FROM SRIRAM_RAW.SRIRAM_MACHINES M

LEFT JOIN SRIRAM_RAW.SRIRAM_PRODUCTION_EVENTS E
    ON M.MACHINE_ID = E.MACHINE_ID

GROUP BY
    M.MACHINE_ID,
    M.MACHINE_NAME,
    M.MACHINE_TYPE,
    M.MACHINE_STATUS;

