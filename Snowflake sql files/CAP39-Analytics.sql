    D.DETECTED_AT,

    ROUND(
        D.AFFECTED_QUANTITY * 100.0 /
        NULLIF(D.INSPECTED_QUANTITY, 0), 2
    ) AS AFFECTED_QUANTITY_RATE_PERCENT

FROM SRIRAM_RAW.SRIRAM_DEFECTS D

