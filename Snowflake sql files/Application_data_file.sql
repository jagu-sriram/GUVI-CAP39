CREATE TABLE IF NOT EXISTS SRIRAM_BATCH_REGISTRATIONS (
    REGISTRATION_ID VARCHAR(100) PRIMARY KEY,
    BATCH_ID VARCHAR(100) NOT NULL,
    PRODUCT_ID VARCHAR(100),
    PRODUCTION_LINE VARCHAR(100),
    SHIFT VARCHAR(50),
    PLANNED_QUANTITY NUMBER(12,2),
    PRODUCED_QUANTITY NUMBER(12,2),
    PRODUCTION_DATE DATE,
    STATUS VARCHAR(50),
    REGISTERED_BY VARCHAR(100),
    REGISTERED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PROCESSING_STATUS VARCHAR(30) DEFAULT 'PENDING'
);

CREATE TABLE IF NOT EXISTS SRIRAM_DEFECT_REGISTRATIONS (
    REGISTRATION_ID VARCHAR(100) PRIMARY KEY,
    DEFECT_ID VARCHAR(100) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    INSPECTION_ID VARCHAR(100),
    DEFECT_CATEGORY VARCHAR(100),
    DEFECT_CODE VARCHAR(100),
    AFFECTED_QUANTITY NUMBER(12,2),
    INSPECTED_QUANTITY NUMBER(12,2),
    DETECTED_AT TIMESTAMP_NTZ,
    SEVERITY VARCHAR(50),
    REGISTERED_BY VARCHAR(100),
    REGISTERED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PROCESSING_STATUS VARCHAR(30) DEFAULT 'PENDING'
);

CREATE TABLE IF NOT EXISTS SRIRAM_FILE_UPLOADS (
    UPLOAD_ID VARCHAR(100) PRIMARY KEY,
    FILE_NAME VARCHAR(255) NOT NULL,
    DATASET_NAME VARCHAR(100),
    FILE_PATH VARCHAR(1000),
    UPLOADED_BY VARCHAR(100),
    UPLOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    TOTAL_RECORDS NUMBER,
    ACCEPTED_RECORDS NUMBER,
    REJECTED_RECORDS NUMBER,
    UPLOAD_STATUS VARCHAR(30) DEFAULT 'RECEIVED',
    ERROR_MESSAGE VARCHAR(2000)
);

CREATE TABLE IF NOT EXISTS SRIRAM_INVESTIGATIONS (
    INVESTIGATION_ID VARCHAR(100) PRIMARY KEY,
    BATCH_ID VARCHAR(100) NOT NULL,
    DEFECT_ID VARCHAR(100),
    SUSPECTED_CAUSE VARCHAR(1000),
    INVESTIGATION_STATUS VARCHAR(30) DEFAULT 'OPEN',
    CONFIRMED_CAUSE VARCHAR(1000),
    INVESTIGATION_NOTES VARCHAR(5000),
    EVIDENCE_REFERENCE VARCHAR(1000),
    INVESTIGATED_BY VARCHAR(100),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

