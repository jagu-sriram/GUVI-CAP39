CREATE OR REPLACE VIEW SRIRAM_VW_YIELD_LOSS_ANALYSIS AS
SELECT
    BATCH_ID,
    PRODUCT_ID,
    PRODUCT_NAME,
    PRODUCTION_LINE,
    LINE_NAME,
    SHIFT,
    PRODUCTION_DATE,

    PLANNED_QUANTITY,
    PRODUCED_QUANTITY,

    GREATEST(
        PLANNED_QUANTITY - PRODUCED_QUANTITY, 0
    ) AS PRODUCTION_SHORTFALL,

    GREATEST(
        PRODUCED_QUANTITY - PLANNED_QUANTITY, 0
    ) AS PRODUCTION_ABOVE_PLAN,

    QUANTITY_VARIANCE,
    PRODUCTION_ATTAINMENT_PERCENT,

    DEFECT_COUNT,
    TOTAL_AFFECTED_QUANTITY,
    TOTAL_INSPECTED_QUANTITY,
    AFFECTED_QUANTITY_RATE_PERCENT,

    CASE
        WHEN PLANNED_QUANTITY > PRODUCED_QUANTITY
        THEN 'BELOW_PLAN'
        WHEN PLANNED_QUANTITY < PRODUCED_QUANTITY
        THEN 'ABOVE_PLAN'
        ELSE 'ON_PLAN'
    END AS PRODUCTION_PERFORMANCE_STATUS

FROM SRIRAM_VW_BATCH_PERFORMANCE;

CREATE OR REPLACE VIEW SRIRAM_VW_ROOT_CAUSE_CANDIDATES AS

WITH BATCH_METRICS AS (
    SELECT
        BATCH_ID,
        PRODUCT_ID,
        PRODUCT_NAME,
        PRODUCTION_LINE,
        LINE_NAME,
        SHIFT,
        DEFECT_COUNT,
        TOTAL_AFFECTED_QUANTITY,
        TOTAL_INSPECTED_QUANTITY,
        AFFECTED_QUANTITY_RATE_PERCENT
    FROM SRIRAM_VW_BATCH_PERFORMANCE
),


PARAMETER_METRICS AS (
    SELECT
        PP.BATCH_ID,
        PP.MACHINE_ID,
        M.MACHINE_NAME,
        PP.PARAMETER_NAME,
        PP.UNIT,

        COUNT(*) AS MEASUREMENT_COUNT,

        ROUND(AVG(PP.PARAMETER_VALUE), 3)
            AS AVG_PARAMETER_VALUE,

        MIN(PP.PARAMETER_VALUE)
            AS MIN_PARAMETER_VALUE,

        MAX(PP.PARAMETER_VALUE)
            AS MAX_PARAMETER_VALUE

    FROM SRIRAM_RAW.SRIRAM_PROCESS_PARAMETERS PP

    LEFT JOIN SRIRAM_RAW.SRIRAM_MACHINES M
        ON PP.MACHINE_ID = M.MACHINE_ID

    GROUP BY
        PP.BATCH_ID,
        PP.MACHINE_ID,
        M.MACHINE_NAME,
        PP.PARAMETER_NAME,
        PP.UNIT
),

MATERIAL_METRICS AS (
    SELECT
        BATCH_ID,
        COUNT(DISTINCT MATERIAL_LOT_ID) AS MATERIAL_LOT_COUNT,
        LISTAGG(DISTINCT MATERIAL_LOT_ID, ', ')
            WITHIN GROUP (ORDER BY MATERIAL_LOT_ID)
            AS MATERIAL_LOTS
    FROM SRIRAM_RAW.SRIRAM_PRODUCTION_EVENTS
    WHERE MATERIAL_LOT_ID IS NOT NULL
    GROUP BY BATCH_ID
),

CANDIDATE_METRICS AS (
    SELECT
        P.*,
        B.PRODUCT_ID,
        B.PRODUCT_NAME,
        B.PRODUCTION_LINE,
        B.LINE_NAME,
        B.SHIFT,

        COALESCE(B.DEFECT_COUNT, 0) AS DEFECT_COUNT,
        COALESCE(B.TOTAL_AFFECTED_QUANTITY, 0)
            AS TOTAL_AFFECTED_QUANTITY,
        B.TOTAL_INSPECTED_QUANTITY,
        B.AFFECTED_QUANTITY_RATE_PERCENT,

        COALESCE(M.MATERIAL_LOT_COUNT, 0)
            AS MATERIAL_LOT_COUNT,
        M.MATERIAL_LOTS,

        AVG(B.AFFECTED_QUANTITY_RATE_PERCENT)
            OVER (
                PARTITION BY P.PARAMETER_NAME, P.MACHINE_ID
            ) AS AVG_RATE_FOR_PARAMETER_MACHINE,

        COUNT(B.AFFECTED_QUANTITY_RATE_PERCENT)
            OVER (
                PARTITION BY P.PARAMETER_NAME, P.MACHINE_ID
            ) AS COMPARABLE_BATCH_COUNT

    FROM PARAMETER_METRICS P

    LEFT JOIN BATCH_METRICS B
        ON P.BATCH_ID = B.BATCH_ID

    LEFT JOIN MATERIAL_METRICS M
        ON P.BATCH_ID = M.BATCH_ID
)

SELECT
    *,

    CASE
        WHEN AFFECTED_QUANTITY_RATE_PERCENT IS NULL
            THEN 'INSUFFICIENT_DEFECT_DATA'

        WHEN COMPARABLE_BATCH_COUNT < 2
            THEN 'INSUFFICIENT_COMPARISON_DATA'

        WHEN AFFECTED_QUANTITY_RATE_PERCENT >
             AVG_RATE_FOR_PARAMETER_MACHINE
            THEN 'ABOVE_COMPARISON_AVERAGE'

        ELSE 'AT_OR_BELOW_COMPARISON_AVERAGE'
    END AS ROOT_CAUSE_CANDIDATE_STATUS

FROM CANDIDATE_METRICS;

SELECT *
